## 麻屑是什么，为什么重要

麻屑是打麻时被击碎并（大部分）清除的木质茎芯碎片。残留的部分会随纤维进入您的工序——每一克麻屑都是按纤维价格买来的，而且是设备必须处理的缺陷。纺纱中，麻屑造成断头和棉结；在外观敏感的应用里，它显现为深色斑点。

## A 级

**洁净、梳理良好、无麻屑。**A 级供给追求高支数的纺纱厂和我们自己的梳麻线——只有原料足够干净，梳麻才有经济意义。如果您的最终产品是细支亚麻纱或任何表面敏感的产品，A 级不是奢侈，而是标配。

## B 级

**洁净度较低、价格较低。**B 级麻屑更多、梳理均匀度稍差。这不是缺陷——而是按用途定位的产品。粗支纱、毛毡、产业用途以及自带清理工序的生产线都可以使用 B 级，省下差价。

## C 级

**入门级。**C 级麻屑含量最高、价格最低。它存在的理由很实在：有些工序反正要自己清理纤维，有些产品根本不需要精整纤维。如果这正是您的生产线，买 A 级等于花两遍钱。

## 如何验包

1. **开包看中间，别看表面。**任何麻包外表都好看。
2. **抓一把在深色纸上抖。**掉落的麻屑比任何证书都说明问题。
3. **检查纤维长度与梳理度。**A 级应能抽出长而平行的纤维，缠结短麻极少。
4. **闻一闻。**干净的亚麻是干草味。霉味说明沤麻或仓储环节受潮。

