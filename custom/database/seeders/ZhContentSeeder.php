## 混纺比例放多少？

没有唯一答案——取决于两点：

1. **亚麻纤维的细度。**纤维越细，可承受的比例越高。
2. **目标纱线。**粗支纱能容纳更多亚麻；细支纱要少放。

实际生产中，纺纱厂将 **10% 至 50% 以上**的亚麻与棉、涤纶或粘胶混纺。服装用纱通常从 15–30% 起步：足以带来干爽、有质感的亚麻手感和天然竹节风格，同时棉保证纱线强力与均匀度。

